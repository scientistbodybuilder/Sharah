
import type { ClauseCardProps } from '../components/analyze/ClauseCard'
import pdfMake from 'pdfmake/build/pdfmake'
import * as pdfFontsModule from 'pdfmake/build/vfs_fonts'

const pdfFonts = (pdfFontsModule as any).default ?? pdfFontsModule
pdfMake.addVirtualFileSystem(pdfFonts)
import type { Content, TDocumentDefinitions } from 'pdfmake/interfaces'

const RULES_VERSION = 'AAOIFI Shariah Standards No. 19 & 31'
const M_SECTION: [number, number, number, number] = [0, 0, 0, 18]
const M_INDENT: [number, number, number, number] = [12, 0, 0, 0]
// const M_HEADING: [number, number, number, number] = [0, 14, 0, 6]

